using UnityEngine;
using UnityEngine.Rendering;

namespace PocketOrbits.Rendering
{
    public enum MaterialKind
    {
        /// <summary>Opaque, lit (planets, beacons, asteroids).</summary>
        Lit = 0,
        /// <summary>Opaque, unlit (emissive star cores).</summary>
        Unlit = 1,
        /// <summary>Alpha blended, vertex colour (regions, rings, lines, background).</summary>
        Transparent = 2,
        /// <summary>Additive, vertex colour (glows, particles, trajectories).</summary>
        Additive = 3,
    }

    /// <summary>
    /// Creates the handful of shared materials the game uses. Prefers material assets generated by
    /// "Pocket Orbits/Set Up Project" (Resources/Materials, which guarantees the shaders are included in builds),
    /// then falls back to Shader.Find with URP and built-in pipeline shader names.
    /// Colours are applied per renderer through MaterialPropertyBlocks, so materials stay shared.
    /// </summary>
    public static class MaterialFactory
    {
        public const string ResourceFolder = "Materials/";

        public static readonly int BaseColorId = Shader.PropertyToID("_BaseColor");
        public static readonly int ColorId = Shader.PropertyToID("_Color");
        public static readonly int TintColorId = Shader.PropertyToID("_TintColor");
        public static readonly int BaseMapId = Shader.PropertyToID("_BaseMap");
        public static readonly int MainTexId = Shader.PropertyToID("_MainTex");
        public static readonly int EmissionColorId = Shader.PropertyToID("_EmissionColor");

        public static string AssetName(MaterialKind kind) => "PO_" + kind;

        public static bool UsingScriptableRenderPipeline => GraphicsSettings.currentRenderPipeline != null;

        static string[] ShaderCandidates(MaterialKind kind)
        {
            switch (kind)
            {
                case MaterialKind.Lit:
                    return new[] { "Universal Render Pipeline/Lit", "Universal Render Pipeline/Simple Lit", "Standard", "Diffuse" };
                case MaterialKind.Unlit:
                    return new[] { "Universal Render Pipeline/Unlit", "Unlit/Color", "Unlit/Texture", "Sprites/Default" };
                case MaterialKind.Transparent:
                    return new[] { "Universal Render Pipeline/Particles/Unlit", "Legacy Shaders/Particles/Alpha Blended", "Particles/Alpha Blended", "Sprites/Default" };
                default:
                    return new[] { "Universal Render Pipeline/Particles/Unlit", "Legacy Shaders/Particles/Additive", "Particles/Additive", "Sprites/Default" };
            }
        }

        /// <summary>Loads the generated material asset or builds an equivalent at runtime.</summary>
        public static Material Get(MaterialKind kind)
        {
            var asset = Resources.Load<Material>(ResourceFolder + AssetName(kind));
            if (asset != null) return new Material(asset) { name = AssetName(kind) };
            return Create(kind);
        }

        public static Material Create(MaterialKind kind)
        {
            Shader shader = null;
            bool srp = UsingScriptableRenderPipeline;
            foreach (var name in ShaderCandidates(kind))
            {
                // Do not pick URP shaders when no SRP is active (they render pink), and vice versa for Standard.
                bool isUrp = name.StartsWith("Universal Render Pipeline");
                if (isUrp != srp && name != "Sprites/Default") continue;
                shader = Shader.Find(name);
                if (shader != null) break;
            }
            if (shader == null) shader = Shader.Find("Sprites/Default");
            var m = new Material(shader) { name = AssetName(kind) };
            Configure(m, kind);
            return m;
        }

        /// <summary>Sets blend state and keywords. Shared with the editor setup so generated assets match.</summary>
        public static void Configure(Material m, MaterialKind kind)
        {
            string shaderName = m.shader != null ? m.shader.name : "";
            bool urp = shaderName.StartsWith("Universal Render Pipeline");
            if (kind == MaterialKind.Lit)
            {
                if (m.HasProperty("_Smoothness")) m.SetFloat("_Smoothness", 0.35f);
                if (m.HasProperty("_Glossiness")) m.SetFloat("_Glossiness", 0.35f);
                m.enableInstancing = true;
                return;
            }
            if (kind == MaterialKind.Unlit)
            {
                m.enableInstancing = true;
                return;
            }

            bool additive = kind == MaterialKind.Additive;
            if (urp)
            {
                m.SetFloat("_Surface", 1f);
                m.SetFloat("_Blend", additive ? 2f : 0f);
                m.SetFloat("_SrcBlend", (float)BlendMode.SrcAlpha);
                m.SetFloat("_DstBlend", additive ? (float)BlendMode.One : (float)BlendMode.OneMinusSrcAlpha);
                if (m.HasProperty("_SrcBlendAlpha")) m.SetFloat("_SrcBlendAlpha", (float)BlendMode.One);
                if (m.HasProperty("_DstBlendAlpha")) m.SetFloat("_DstBlendAlpha", additive ? (float)BlendMode.One : (float)BlendMode.OneMinusSrcAlpha);
                m.SetFloat("_ZWrite", 0f);
                m.SetOverrideTag("RenderType", "Transparent");
                m.EnableKeyword("_SURFACE_TYPE_TRANSPARENT");
                m.DisableKeyword("_ALPHAPREMULTIPLY_ON");
                m.DisableKeyword("_ALPHAMODULATE_ON");
                m.SetShaderPassEnabled("ShadowCaster", false);
                m.SetShaderPassEnabled("DepthOnly", false);
            }
            m.renderQueue = (int)RenderQueue.Transparent;
        }

        /// <summary>Writes a colour into every colour slot the supported shaders use.</summary>
        public static void SetColor(MaterialPropertyBlock block, Color c)
        {
            block.SetColor(BaseColorId, c);
            block.SetColor(ColorId, c);
            // Legacy particle shaders compute 2 * _TintColor * vertex colour, so halve every channel.
            block.SetColor(TintColorId, c * 0.5f);
        }

        public static void SetTexture(MaterialPropertyBlock block, Texture t)
        {
            if (t == null) return;
            block.SetTexture(BaseMapId, t);
            block.SetTexture(MainTexId, t);
        }
    }
}
